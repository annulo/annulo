/**
 * 按模型标识匹配厂商：传模型 id、展示名。匹配不到返回 null，由调用方兜底展示首字母。
 */
export function getLlmModelBrand(...candidates: Array<string | undefined>): LlmModelBrand | null {
  const text = candidates
    .map((item) => item?.trim().toLowerCase())
    .filter(Boolean)
    .join(' ')
  if (!text) return null

  for (const brand of BRANDS) {
    if (brand.test.test(text)) {
      const { test: _test, ...rest } = brand
      return rest
    }
  }
  return null
}

/** 模型的厂商 logo；认不出厂商返回 undefined，由调用方兜底（比如 Select 显示首字母） */
export function ModelIcon({ m }: { m: ModelConfig }) {
  const b = getLlmModelBrand(m.model, m.name, m.label)
  if (!b) return undefined
  return (
    <svg viewBox="0 0 24 24" className="size-3.5 text-foreground/80" fill={b.color} fillRule={b.fillRule} aria-label={b.label}>
      <path d={b.path} />
    </svg>
  )
}

